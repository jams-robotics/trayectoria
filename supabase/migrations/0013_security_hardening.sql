-- #522, #527.4, #527.5 · Storage `urdf` ------------------------------------------------------------
-- Uploads and moves must land on `{uid}/{robotId}.zip`, the only key the client writes
-- (`urdfObjectPath`), and need the caller's profile: a JWT still valid after `delete_account()`
-- has no profile, so it cannot leave orphan objects under a deleted uid. The bucket takes only
-- `application/zip`, the content type the client sends. Reads and deletes keep the folder rule.
-- Orphan prefixes are not swept by a periodic job in v1.

update storage.buckets set allowed_mime_types = array['application/zip'] where id = 'urdf';

alter policy "urdf: owner reads" on storage.objects
  using (bucket_id = 'urdf' and (storage.foldername(name))[1] = (select auth.uid())::text);

alter policy "urdf: owner uploads" on storage.objects
  with check (
    bucket_id = 'urdf'
    and name ~ ('^' || (select auth.uid())::text || '/[0-9a-f-]{36}\.zip$')
    and exists (select 1 from public.profiles p where p.id = (select auth.uid()))
  );

alter policy "urdf: owner updates" on storage.objects
  using (bucket_id = 'urdf' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (
    bucket_id = 'urdf'
    and name ~ ('^' || (select auth.uid())::text || '/[0-9a-f-]{36}\.zip$')
    and exists (select 1 from public.profiles p where p.id = (select auth.uid()))
  );

alter policy "urdf: owner deletes" on storage.objects
  using (bucket_id = 'urdf' and (storage.foldername(name))[1] = (select auth.uid())::text);

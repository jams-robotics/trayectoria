      constraint = 'group_members_owner_row_limit',
      message = 'new row for relation "group_members" violates check constraint "group_members_owner_row_limit"';
  end if;
  return new;
end;
$$;

revoke all on function public.enforce_progress_owner_limit() from public, anon, authenticated;
revoke all on function public.enforce_groups_owner_limit() from public, anon, authenticated;
revoke all on function public.enforce_group_members_owner_limit() from public, anon, authenticated;

create trigger progress_owner_row_limit

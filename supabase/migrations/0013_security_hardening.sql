-- Trayectoria · database and storage hardening (security audit 2026-09-26; lote SEC-DB).
-- #508 (invite codes and join_group), #509 (column and row bounds), #522 (storage `urdf`) and the
-- points of #527 that need a migration (listed in PR #632). No earlier migration is edited: every
-- change is an `alter`, a `create or replace` or a drop and re-create here.
--
-- Every new bound follows the pattern of 0007/0008: a check constraint, or a `before insert`
-- trigger that raises `23514` with the name of the limit as the constraint, so the client tells
-- them apart by that name. Check constraints are validated against the existing rows: if one were
-- already out of bounds, the migration would fail here instead of leaving a table that breaks its
-- own constraint.

-- #527.1 · New relations and functions in `public` are closed to `anon` by default -------------
-- `revoke all on all tables ... from anon` (0002) only covered the tables that existed then; each
-- later migration revoked by hand. The default privileges of the migration role still granted
-- `anon` everything on new tables, sequences and functions.

alter default privileges for role postgres in schema public revoke all on tables from anon;
alter default privileges for role postgres in schema public revoke all on sequences from anon;
alter default privileges for role postgres in schema public revoke all on functions from anon;

-- #527.2 · `set_updated_at` is a trigger function; PostgREST would list it as RPC (as in 0008).
revoke all on function public.set_updated_at() from public, anon, authenticated;

-- #508 · Invite codes are generated by the database ----------------------------------------------
-- The client generated the code and wrote it, so any teacher could set `invite_code = 'A'`, and
-- the unique index answered `23505` for an existing code (an oracle without joining). Now the code
-- comes only from `generate_invite_code()`: 8 characters of the dictation-friendly alphabet the
-- classroom already uses (no I, O, 0 or 1), from `gen_random_bytes`. 256 is a multiple of 32, so
-- `byte % 32` is uniform. `authenticated` keeps insert on `id`, `owner_id`, `name` and update on
-- `name` only; the code is set by the column default on insert and by `regenerate_invite_code()`.

create function public.generate_invite_code() returns text
language sql volatile set search_path = '' as $$
  select string_agg(
    substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', get_byte(r.bytes, i.position) % 32 + 1, 1),
    '' order by i.position
  )
  from (select extensions.gen_random_bytes(8) as bytes) as r,
       generate_series(0, 7) as i (position);
$$;

-- The column default calls it with the privileges of the inserting user, so `authenticated` keeps
-- `execute`: as an RPC it only returns a random string, never an existing code.
revoke all on function public.generate_invite_code() from public, anon;
grant execute on function public.generate_invite_code() to authenticated;

alter table public.groups alter column invite_code set default public.generate_invite_code();
alter table public.groups
  add constraint groups_invite_code_format check (invite_code ~ '^[A-Z0-9]{8,}$');

revoke insert, update on public.groups from authenticated;
grant insert (id, owner_id, name) on public.groups to authenticated;
grant update (name) on public.groups to authenticated;

-- The owner replaces the code of their group. A collision with another group's code (1 in 2^40
-- per existing group) draws again, at most five times.
create function public.regenerate_invite_code(target_group_id uuid) returns text
language plpgsql security definer set search_path = '' as $$
declare
  new_code text;
begin
  if not public.owns_group(target_group_id) then
    raise exception 'group not found' using errcode = 'P0001';
  end if;
  for draw in 1..5 loop
    new_code := public.generate_invite_code();
    begin
      update public.groups set invite_code = new_code where id = target_group_id;
      return new_code;
    exception when unique_violation then
      null;
    end;
  end loop;
  raise exception 'invite code collision' using errcode = 'P0001';
end;
$$;

revoke all on function public.regenerate_invite_code(uuid) from public, anon;
grant execute on function public.regenerate_invite_code(uuid) to authenticated;

-- #508 · Failed attempts of join_group ------------------------------------------------------------
-- At most 10 failed joins per user in 10 minutes. The failures are rows of `join_attempts`, which
-- no API role can read or write. A failed join now returns `null` instead of raising: a raise
-- would roll back the row that counts the failure, so the limit would never be reached. Unknown
-- code, own group and existing membership still give the same answer. Past the limit the function
-- raises `too many join attempts` before looking at the code. The rows older than the window are
-- deleted on every call of the same user, so there is no periodic clean-up.

create table public.join_attempts (
  user_id uuid not null references public.profiles (id) on delete cascade,
  attempted_at timestamptz not null default now()
);

create index join_attempts_user_id_attempted_at_idx
  on public.join_attempts (user_id, attempted_at);

alter table public.join_attempts enable row level security;
revoke all on public.join_attempts from anon, authenticated;

create or replace function public.join_group(invite_code text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := auth.uid();
  found_group_id uuid;
  found_owner_id uuid;
begin
  if caller_id is null then
    raise exception 'invalid invite code' using errcode = 'P0001';
  end if;

  -- Concurrent calls of the same user count one after the other.
  perform pg_advisory_xact_lock(hashtextextended('join_group:' || caller_id::text, 0));
  delete from public.join_attempts
   where user_id = caller_id and attempted_at < now() - interval '10 minutes';
  if (select count(*) from public.join_attempts where user_id = caller_id) >= 10 then
    raise exception 'too many join attempts' using errcode = 'P0001';
  end if;

  select g.id, g.owner_id
    into found_group_id, found_owner_id
    from public.groups g
   where g.invite_code = join_group.invite_code;

  if found_group_id is null
     or found_owner_id = caller_id
     or exists (
       select 1 from public.group_members m
        where m.group_id = found_group_id and m.user_id = caller_id
     )
  then
    insert into public.join_attempts (user_id) values (caller_id);
    return null;
  end if;

  insert into public.group_members (group_id, user_id) values (found_group_id, caller_id);
  return found_group_id;
end;
$$;


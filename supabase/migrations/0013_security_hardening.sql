-- #509.6 · A huge name in the sign-up metadata is cut, not a failed sign-up. Same body as 0010.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(
      nullif(trim(left(trim(new.raw_user_meta_data ->> 'display_name'), 80)), ''),
      'Estudiante'
    ),
    case when new.raw_user_meta_data ->> 'role' = 'teacher' then 'teacher' else 'student' end
  );
  return new;
end;
$$;

-- #509.5 · Rows per owner: 500 progress rows per learner, 50 groups per teacher, 50 memberships
-- per user. Same shape as 0008. `progress` is written with an upsert on `(user_id, topic_id)`, so
-- writing an existing topic again adds no row and is let through, like `tracks` in 0008.
-- Memberships are inserted by `join_group` as the function owner, so that count is not under RLS.

create function public.enforce_progress_owner_limit() returns trigger
language plpgsql set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('progress:' || new.user_id::text, 0));
  if exists (
    select 1 from public.progress where user_id = new.user_id and topic_id = new.topic_id
  ) then
    return new;
  end if;
  if (select count(*) from public.progress where user_id = new.user_id) >= 500 then
    raise exception using
      errcode = 'check_violation',
      constraint = 'progress_owner_row_limit',
      message = 'new row for relation "progress" violates check constraint "progress_owner_row_limit"';
  end if;
  return new;
end;
$$;

create function public.enforce_groups_owner_limit() returns trigger
language plpgsql set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('groups:' || new.owner_id::text, 0));
  if (select count(*) from public.groups where owner_id = new.owner_id) >= 50 then
    raise exception using
      errcode = 'check_violation',
      constraint = 'groups_owner_row_limit',
      message = 'new row for relation "groups" violates check constraint "groups_owner_row_limit"';
  end if;
  return new;
end;
$$;

create function public.enforce_group_members_owner_limit() returns trigger
language plpgsql set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('group_members:' || new.user_id::text, 0));
  if (select count(*) from public.group_members where user_id = new.user_id) >= 50 then
